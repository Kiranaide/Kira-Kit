/**
 * Prebuild: embed the kit's base CSS, vendored utilities, and default theme
 * tokens into src/generated/assets.ts so `kira-kit init` works offline, and
 * sync the same CSS into the bundled create templates.
 *
 * Usage (from packages/cli): bun run scripts/embed-assets.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  buildBaseCss,
  defaultThemeItem,
} from "../src/core/registry/css-assets";

const REPO_ROOT = resolve(
  fileURLToPath(new URL(".", import.meta.url)),
  "../../..",
);

const indexCss = readFileSync(
  join(REPO_ROOT, "src/index.css"),
  "utf-8",
).replaceAll("\r\n", "\n");

const utilities = readFileSync(
  join(REPO_ROOT, "src/styles/kira-utilities.css"),
  "utf-8",
).replaceAll("\r\n", "\n");

const theme = defaultThemeItem(indexCss);

const lines = [
  "// Generated by scripts/embed-assets.ts — do not edit by hand.",
  "",
  `export const BASE_CSS = ${JSON.stringify(buildBaseCss(indexCss, "./kira-utilities.css"))};`,
  "",
  `export const UTILITIES_CSS = ${JSON.stringify(utilities)};`,
  "",
  `export const DEFAULT_THEME_CSSVARS = ${JSON.stringify(theme.cssVars, null, 2)};`,
  "",
];

const outDir = resolve(
  fileURLToPath(new URL(".", import.meta.url)),
  "../src/generated",
);

mkdirSync(outDir, { recursive: true });

writeFileSync(join(outDir, "assets.ts"), lines.join("\n"), "utf-8");

console.log("Embedded kit CSS assets into src/generated/assets.ts.");

const TEMPLATES_ROOT = resolve(
  fileURLToPath(new URL(".", import.meta.url)),
  "../templates",
);

/** Template CSS entry points and where their utilities copy lives. */
const TEMPLATE_CSS_TARGETS = [
  {
    css: "vite/src/index.css",
    utilities: "vite/src/styles/kira-utilities.css",
    utilitiesImport: "./styles/kira-utilities.css",
  },
  {
    css: "tanstack-start/src/index.css",
    utilities: "tanstack-start/src/styles/kira-utilities.css",
    utilitiesImport: "./styles/kira-utilities.css",
  },
  {
    css: "next/app/globals.css",
    utilities: "next/app/kira-utilities.css",
    utilitiesImport: "./kira-utilities.css",
  },
  {
    css: "monorepo/packages/ui/src/index.css",
    utilities: "monorepo/packages/ui/src/styles/kira-utilities.css",
    utilitiesImport: "./styles/kira-utilities.css",
  },
] as const;

for (const target of TEMPLATE_CSS_TARGETS) {
  const cssPath = join(TEMPLATES_ROOT, target.css);
  const utilitiesPath = join(TEMPLATES_ROOT, target.utilities);

  mkdirSync(resolve(cssPath, ".."), { recursive: true });
  mkdirSync(resolve(utilitiesPath, ".."), { recursive: true });
  writeFileSync(
    cssPath,
    buildBaseCss(indexCss, target.utilitiesImport),
    "utf-8",
  );
  writeFileSync(utilitiesPath, utilities, "utf-8");
}

console.log(`Synced kit CSS into ${TEMPLATE_CSS_TARGETS.length} templates.`);
