import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildBaseCss, defaultThemeItem } from "./stylesheet";

export interface SyncEmbeddedAssetsResult {
  assetsWritten: boolean;
}

/**
 * Sync src/index.css and src/styles/kira-utilities.css into
 * packages/cli/src/generated/assets.ts so `kira-kit init` works offline.
 * No-ops cleanly when run outside the monorepo (e.g. a mini-repo fixture).
 */
export function syncEmbeddedAssets(repoRoot: string): SyncEmbeddedAssetsResult {
  const indexCssPath = join(repoRoot, "src/index.css");
  const utilitiesPath = join(repoRoot, "src/styles/kira-utilities.css");
  const cliRoot = join(repoRoot, "packages/cli");

  if (
    !existsSync(indexCssPath) ||
    !existsSync(utilitiesPath) ||
    !existsSync(cliRoot)
  ) {
    return { assetsWritten: false };
  }

  const indexCss = readFileSync(indexCssPath, "utf-8").replaceAll("\r\n", "\n");

  const utilities = readFileSync(utilitiesPath, "utf-8").replaceAll(
    "\r\n",
    "\n",
  );

  const theme = defaultThemeItem(indexCss);

  const lines = [
    "// Generated by scripts/embed-assets.ts — do not edit by hand.",
    "",
    `export const BASE_CSS = ${JSON.stringify(buildBaseCss(indexCss, "./kira-utilities.css"))};`,
    "",
    `export const UTILITIES_CSS = ${JSON.stringify(utilities)};`,
    "",
    `export const DEFAULT_THEME_CSSVARS = ${JSON.stringify(theme.cssVars, null, 2)};`,
    "",
  ];

  const generatedDir = join(cliRoot, "src/generated");
  mkdirSync(generatedDir, { recursive: true });
  writeFileSync(join(generatedDir, "assets.ts"), lines.join("\n"), "utf-8");

  return { assetsWritten: true };
}
