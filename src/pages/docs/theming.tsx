import { useState, type CSSProperties } from "react";
import { Link } from "@tanstack/react-router";
import { IconSun, IconMoon, IconArrowRight } from "@tabler/icons-react";
import { cn } from "cn";
import { Badge } from "@/components/ui/badge";
import { Button, buttonVariants } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { CodeBlock } from "@/components/ui/code-block";
import { Input } from "@/components/ui/input";
import { Progress } from "@/components/ui/progress";
import { ComponentPage, PageHeader, Section } from "@/components/docs";
import themesRegistry from "@/themes/registry.json";

interface ThemeRegistryItem {
  name: string;
  type: string;
  title: string;
  description: string;
  cssVars: {
    theme?: Record<string, string>;
    light: Record<string, string>;
    dark: Record<string, string>;
  };
}

// SAFETY: src/themes/registry.json is generated by kira-kit build; every
// registry:theme item carries title/description and cssVars light/dark maps.
const themeItems = (themesRegistry.items as ThemeRegistryItem[]).filter(
  (item) => item.type === "registry:theme",
);

const presetMeta = [
  { slug: "ember-press", primary: "#A54932", family: "Warm / editorial" },
  { slug: "oxblood-atelier", primary: "#7E3548", family: "Warm / editorial" },
  { slug: "olive-ledger", primary: "#5F6738", family: "Warm / editorial" },
  { slug: "laurel-study", primary: "#315C4E", family: "Warm / editorial" },
  { slug: "phase-line", primary: "#0B7F79", family: "Cool / technical" },
  { slug: "cryostat", primary: "#007C91", family: "Cool / technical" },
  { slug: "low-orbit", primary: "#3B5F82", family: "Cool / technical" },
  { slug: "coral-circuit", primary: "#F2555A", family: "Bold / expressive" },
  { slug: "magenta-riot", primary: "#B91668", family: "Bold / expressive" },
];

function metaFor(slug: string) {
  return presetMeta.find((entry) => entry.slug === slug);
}

const tokenGroups = [
  {
    tokens: ["--background", "--foreground"],
    purpose: "Page surface and default text color.",
  },
  {
    tokens: ["--card", "--popover"],
    purpose: "Elevated surfaces: cards, popovers, dialogs, menus.",
  },
  {
    tokens: ["--primary", "--primary-foreground"],
    purpose: "Brand accent for primary actions and selected states.",
  },
  {
    tokens: ["--secondary", "--muted", "--accent"],
    purpose:
      "Supporting surfaces: secondary buttons, subtle fills, hover states.",
  },
  {
    tokens: ["--destructive", "--success", "--warning", "--info"],
    purpose: "Semantic feedback colors, each with a paired foreground.",
  },
  {
    tokens: ["--border", "--input", "--ring"],
    purpose: "Hairlines, control borders, and the focus ring.",
  },
  {
    tokens: ["--chart-1", "--chart-2", "--chart-3", "--chart-4", "--chart-5"],
    purpose: "A five-hue categorical palette for data visualization.",
  },
  {
    tokens: ["--sidebar", "--sidebar-primary", "--sidebar-accent"],
    purpose: "Sidebar-specific surface and accent tokens.",
  },
  {
    tokens: ["--radius"],
    purpose: "Base corner radius; the whole radius ladder derives from it.",
  },
];

const radiusSteps = [
  { className: "rounded-sm", label: "sm", note: "radius − 4px" },
  { className: "rounded-md", label: "md", note: "radius − 2px" },
  { className: "rounded-lg", label: "lg", note: "radius" },
  { className: "rounded-xl", label: "xl", note: "radius + 4px" },
  { className: "rounded-2xl", label: "2xl", note: "radius + 8px" },
];

const customThemeCode = `# Print a full palette derived from one primary color
npx kira-kit theme --primary "#0B7F79"

# Install it into the project (light + dark schemes)
npx kira-kit theme --primary "#0B7F79" --apply

# Choose the neutral family and export to a file
npx kira-kit theme --primary "#7E3548" --base-color mauve --out theme.json`;

const darkModeCode = `/* index.css — tokens flip when .dark is present on <html> */
:root {
  --background: oklch(1 0 0);
  --foreground: oklch(0.145 0 0);
}
.dark {
  --background: oklch(0.145 0 0);
  --foreground: oklch(0.985 0 0);
}`;

function PresetPreview({
  item,
  mode,
}: {
  item: ThemeRegistryItem;
  mode: "light" | "dark";
}) {
  // SAFETY: cssVars maps contain only CSS custom properties (--*), which
  // React passes through to the style attribute verbatim.
  const style = {
    ...item.cssVars[mode],
    ...item.cssVars.theme,
  } as CSSProperties;

  return (
    <div
      style={style}
      className="space-y-4 rounded-xl border border-border bg-background p-6 text-foreground"
    >
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div>
          <p className="text-base font-semibold">{item.title}</p>
          <p className="text-sm text-muted-foreground">
            Every element below reads the preset&apos;s tokens.
          </p>
        </div>
        <Badge variant="secondary">{mode}</Badge>
      </div>
      <div className="flex flex-wrap gap-2">
        <Button size="sm">Primary</Button>
        <Button size="sm" variant="secondary">
          Secondary
        </Button>
        <Button size="sm" variant="outline">
          Outline
        </Button>
        <Button size="sm" variant="destructive">
          Destructive
        </Button>
      </div>
      <div className="flex flex-wrap gap-2">
        <Badge>Default</Badge>
        <Badge variant="success">Success</Badge>
        <Badge variant="warning">Warning</Badge>
        <Badge variant="info">Info</Badge>
      </div>
      <Input placeholder="Inputs inherit the same tokens" />
      <Progress value={64} aria-label="Example progress" />
      <div className="flex gap-2" aria-hidden="true">
        {[
          "bg-chart-1",
          "bg-chart-2",
          "bg-chart-3",
          "bg-chart-4",
          "bg-chart-5",
        ].map((chartClass) => (
          <div
            key={chartClass}
            className={cn("h-4 flex-1 rounded", chartClass)}
          />
        ))}
      </div>
    </div>
  );
}

export default function ThemingPage() {
  const [selectedName, setSelectedName] = useState("theme-phase-line");
  const [mode, setMode] = useState<"light" | "dark">("light");

  const selected =
    themeItems.find((item) => item.name === selectedName) ?? themeItems[0];

  const slug = selected.name.replace("theme-", "");
  const meta = metaFor(slug);

  return (
    <ComponentPage>
      <PageHeader
        title="Theming"
        description="Kira Kit themes are plain CSS variables in OKLCH. Nine curated presets ship with the registry, and the CLI generates a contrast-verified palette from any primary color you choose."
        badge={<Badge variant="secondary">OKLCH</Badge>}
      />

      <Section
        title="Theme presets"
        description="Pick a preset to preview it live — the panel below renders real kit components under that preset's tokens, in light or dark. Nothing on the rest of this page changes."
      >
        <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {themeItems.map((item) => {
            const itemSlug = item.name.replace("theme-", "");
            const itemMeta = metaFor(itemSlug);
            const isSelected = item.name === selected.name;

            return (
              <button
                key={item.name}
                type="button"
                aria-pressed={isSelected}
                onClick={() => setSelectedName(item.name)}
                className={cn(
                  "cursor-pointer rounded-lg border border-border bg-card p-4 text-left transition-colors hover:bg-accent/50 focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ring",
                  isSelected && "border-primary ring-2 ring-ring",
                )}
              >
                <span className="flex items-center gap-2">
                  <span
                    className="h-4 w-4 shrink-0 rounded-full border border-border"
                    style={{ backgroundColor: itemMeta?.primary }}
                    aria-hidden="true"
                  />
                  <span className="font-medium">{item.title}</span>
                </span>
                <span className="mt-1 block text-xs text-muted-foreground">
                  {itemMeta?.family} · {itemMeta?.primary}
                </span>
              </button>
            );
          })}
        </div>

        <Card>
          <CardHeader className="border-b">
            <div className="flex flex-col items-start gap-3 sm:flex-row sm:items-center sm:justify-between">
              <div className="min-w-0">
                <CardTitle>Live preview</CardTitle>
                <CardDescription>{selected.description}</CardDescription>
              </div>
              <div className="flex gap-2">
                <Button
                  size="sm"
                  variant={mode === "light" ? "default" : "outline"}
                  aria-pressed={mode === "light"}
                  onClick={() => setMode("light")}
                  leftIcon={<IconSun className="h-4 w-4" aria-hidden="true" />}
                >
                  Light
                </Button>
                <Button
                  size="sm"
                  variant={mode === "dark" ? "default" : "outline"}
                  aria-pressed={mode === "dark"}
                  onClick={() => setMode("dark")}
                  leftIcon={<IconMoon className="h-4 w-4" aria-hidden="true" />}
                >
                  Dark
                </Button>
              </div>
            </div>
          </CardHeader>
          <CardContent className="space-y-4 pt-6">
            <PresetPreview item={selected} mode={mode} />
            <CodeBlock
              code={`npx shadcn@latest add @kira-kit/${selected.name}\n# or apply it during setup:\nnpx kira-kit init --preset ${slug}`}
              language="bash"
              copyFormat="shell"
              filename={`install ${selected.title}`}
            />
          </CardContent>
        </Card>
      </Section>

      <Section
        title="Generate a custom theme"
        description="The same OKLCH engine that builds the presets runs locally. Give it a primary color; it derives light and dark schemes, chart hues, and a neutral family."
      >
        <Card>
          <CardContent className="space-y-4 pt-6">
            <CodeBlock
              code={customThemeCode}
              language="bash"
              copyFormat="shell"
            />
            <p className="text-sm text-muted-foreground">
              Neutral families: neutral, stone, zinc, slate, gray, plus mauve,
              olive, mist, and taupe. Every generated token is checked against
              WCAG 2.2 AA — 4.5:1 for text, 3:1 for UI — with APCA used as a
              perceptual cross-check.
            </p>
          </CardContent>
        </Card>
      </Section>

      <Section
        title="Token anatomy"
        description="Swatches below show the tokens active on this site right now. Toggle the theme in the sidebar to watch them flip."
      >
        <Card>
          <CardContent className="pt-6">
            <div className="overflow-x-auto">
              <table className="w-full text-sm">
                <thead>
                  <tr className="border-b">
                    <th className="py-2 text-left font-medium">Token</th>
                    <th className="py-2 text-left font-medium">Swatch</th>
                    <th className="py-2 text-left font-medium">Purpose</th>
                  </tr>
                </thead>
                <tbody className="divide-y">
                  {tokenGroups.map((group) => (
                    <tr key={group.tokens[0]}>
                      <td className="py-2 font-mono text-xs">
                        {group.tokens.join(", ")}
                      </td>
                      <td className="py-2">
                        <div className="flex gap-1" aria-hidden="true">
                          {group.tokens
                            .filter((token) => token !== "--radius")
                            .map((token) => (
                              <span
                                key={token}
                                className="h-6 w-6 rounded-md border border-border"
                                style={{ background: `var(${token})` }}
                              />
                            ))}
                        </div>
                      </td>
                      <td className="py-2 text-muted-foreground">
                        {group.purpose}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </CardContent>
        </Card>
      </Section>

      <Section
        title="Radius ladder"
        description="One --radius variable drives every corner. This repo uses 0.45rem; presets may ship their own value (Ember Press uses 0.625rem). The ladder below reflects the active theme."
      >
        <div className="grid gap-4 sm:grid-cols-3 lg:grid-cols-5">
          {radiusSteps.map((step) => (
            <Card key={step.label}>
              <CardContent className="flex flex-col items-center gap-2 pt-6">
                <div
                  className={cn(
                    "h-12 w-full border-2 border-primary bg-primary/10",
                    step.className,
                  )}
                  aria-hidden="true"
                />
                <p className="font-mono text-xs">{step.className}</p>
                <p className="text-xs text-muted-foreground">{step.note}</p>
              </CardContent>
            </Card>
          ))}
        </div>
      </Section>

      <Section
        title="Dark mode"
        description="Dark mode is a .dark class on <html>. The kit's ThemeProvider persists the choice to localStorage and respects prefers-color-scheme on first visit — no flash, no prop drilling."
      >
        <Card>
          <CardContent className="pt-6">
            <CodeBlock code={darkModeCode} language="css" />
          </CardContent>
        </Card>
      </Section>

      <div className="flex flex-wrap items-center justify-between gap-4 rounded-xl border border-border bg-muted/30 p-6">
        <p className="text-sm text-muted-foreground">
          {meta
            ? `${selected.title} (${meta.family}) is one command away.`
            : "Presets install as registry:theme items."}{" "}
          See the CLI reference for every theme flag.
        </p>
        <Link
          to="/docs/cli"
          className={cn(buttonVariants({ size: "sm" }), "gap-2")}
        >
          CLI reference
          <IconArrowRight className="h-4 w-4" aria-hidden="true" />
        </Link>
      </div>
    </ComponentPage>
  );
}
